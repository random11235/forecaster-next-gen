// The check between the triage agent's plan and any write (#363, part of #359; ADR 0006). The agent holds no token and
// returns a plan for a batch of issues; this module, which does no I/O, refuses the plan whole, naming every reason, or
// turns it into the writes the apply job performs, in order. Nothing runs it yet.
//
// A duplicate is closed onto the oldest issue it duplicates, which survives: its labels follow its survivor's, and it
// gets no state of its own. Only an issue the plan makes `ready-for-agent` is dispatched to the factory's build, and no
// write adds `in-progress`, which only the build adds.

/** The category roles a triaged issue carries one of (`.claude/skills/triage/SKILL.md`). */
export const CATEGORIES = ['bug', 'enhancement'] as const
export type Category = (typeof CATEGORIES)[number]

/**
 * The states the agent may give an issue: `already-implemented` becomes `wontfix` and a close. A rejection, or anything
 * the agent isn't sure of, is `ready-for-human` (ADR 0006), so `wontfix` itself isn't one.
 */
export const STATES = ['needs-info', 'ready-for-agent', 'ready-for-human', 'already-implemented'] as const
export type State = (typeof STATES)[number]

/**
 * One issue of the agent's plan. A duplicate names the issue it duplicates in `duplicate_of`; its category and state, if
 * it gives them, must be known, but its labels are its survivor's.
 */
export type PlannedIssue =
  | { number: number; category: Category; state: State; comment: string; duplicate_of?: undefined }
  | { number: number; category?: Category; state?: State; comment: string; duplicate_of: number }

/** The agent's plan: an entry for each issue of the batch, once. */
export type TriagePlan = { issues: readonly PlannedIssue[] }

/** The line every comment posted during triage opens with (`.claude/skills/triage/SKILL.md`). */
export const TRIAGE_DISCLAIMER = '> *This was generated by AI during triage.*'

/** The hidden mark on a triage brief, the comment of an issue made `ready-for-agent` or `ready-for-human`. */
export const BRIEF_MARK = '<!-- forecaster-brief -->'

/** A state label the apply job sets, replacing the issue's last one. */
export type StateLabel = Exclude<State, 'already-implemented'> | 'wontfix'

export type Write =
  | { kind: 'comment'; issue: number; body: string }
  | { kind: 'labels'; issue: number; category: Category; state: StateLabel }
  | { kind: 'close-as-duplicate'; issue: number; of: number }
  | { kind: 'close-as-implemented'; issue: number }
  | { kind: 'dispatch'; issue: number }

export type Checked = { accepted: false; reasons: readonly string[] } | { accepted: true; writes: readonly Write[] }

/**
 * The plan for a batch, the batch's issue numbers oldest first, refused with every reason or accepted as its writes:
 * surviving issues before their duplicates, each in the batch's order, and each issue's comment, then its labels, then
 * its close or its dispatch.
 */
export function checkPlan(batch: readonly number[], plan: unknown): Checked {
  if (!isRecord(plan) || !Array.isArray(plan.issues)) return refused(['the plan is not an object with a list of issues'])
  const reasons: string[] = []
  const entries = plan.issues.flatMap((entry: unknown, index): PlannedIssue[] => {
    const problems = entryProblems(entry)
    reasons.push(...problems.map((problem) => `issue ${index + 1} of the plan ${problem}`))
    return problems.length === 0 ? [entry as PlannedIssue] : []
  })
  reasons.push(...batchProblems(batch, entries), ...duplicateProblems(batch, entries))
  if (reasons.length > 0) return refused(reasons)

  const byNumber = new Map(entries.map((entry) => [entry.number, entry]))
  const ordered = batch.flatMap((number) => byNumber.get(number) ?? [])
  const survivors = ordered.filter((entry) => entry.duplicate_of === undefined)
  const duplicates = ordered.filter((entry) => entry.duplicate_of !== undefined)
  return { accepted: true, writes: [...survivors, ...duplicates].flatMap((entry) => writesFor(entry, byNumber)) }
}

const refused = (reasons: readonly string[]): Checked => ({ accepted: false, reasons })

function writesFor(entry: PlannedIssue, byNumber: ReadonlyMap<number, PlannedIssue>): Write[] {
  const issue = entry.number
  if (entry.duplicate_of !== undefined) {
    const survivor = byNumber.get(entry.duplicate_of)
    if (survivor?.duplicate_of !== undefined || !survivor) throw new Error(`#${issue}'s survivor wasn't checked`)
    return [
      { kind: 'comment', issue, body: commentBody(entry.comment, false) },
      { kind: 'labels', issue, category: survivor.category, state: stateLabel(survivor.state) },
      { kind: 'close-as-duplicate', issue, of: survivor.number },
    ]
  }
  const brief = entry.state === 'ready-for-agent' || entry.state === 'ready-for-human'
  const writes: Write[] = [
    { kind: 'comment', issue, body: commentBody(entry.comment, brief) },
    { kind: 'labels', issue, category: entry.category, state: stateLabel(entry.state) },
  ]
  if (entry.state === 'already-implemented') writes.push({ kind: 'close-as-implemented', issue })
  if (entry.state === 'ready-for-agent') writes.push({ kind: 'dispatch', issue })
  return writes
}

const stateLabel = (state: State): StateLabel => (state === 'already-implemented' ? 'wontfix' : state)

const commentBody = (comment: string, brief: boolean): string =>
  [TRIAGE_DISCLAIMER, ...(brief ? [BRIEF_MARK] : []), comment.trim()].join('\n\n')

/** What's wrong with one entry of the plan, each said after "issue <i> of the plan". */
function entryProblems(entry: unknown): string[] {
  if (!isRecord(entry)) return ['is not an object']
  const problems: string[] = []
  const { number, category, state, comment, duplicate_of } = entry
  const duplicate = duplicate_of !== undefined
  if (!isIssueNumber(number)) problems.push(`has no issue number: ${show(number)}`)
  if (duplicate && !isIssueNumber(duplicate_of)) problems.push(`has a duplicate_of that is no issue number: ${show(duplicate_of)}`)
  if (!(duplicate && category === undefined) && !isOneOf(CATEGORIES, category)) problems.push(`has an unknown category: ${show(category)}`)
  if (!(duplicate && state === undefined) && !isOneOf(STATES, state)) problems.push(`has an unknown state: ${show(state)}`)
  if (typeof comment !== 'string' || comment.trim() === '') problems.push('has an empty comment')
  return problems
}

/** Each issue of the batch, and only those, listed once. */
function batchProblems(batch: readonly number[], entries: readonly PlannedIssue[]): string[] {
  const inBatch = new Set(batch)
  const counts = new Map<number, number>()
  for (const { number } of entries) counts.set(number, (counts.get(number) ?? 0) + 1)
  return [
    ...batch.filter((number) => !counts.has(number)).map((number) => `#${number} of the batch is missing from the plan`),
    ...[...counts.keys()].filter((number) => !inBatch.has(number)).map((number) => `#${number} is in the plan but not the batch`),
    ...[...counts].filter(([, count]) => count > 1).map(([number, count]) => `#${number} is in the plan ${count} times`),
  ]
}

/** Each duplicate onto an older issue of the batch that is no duplicate itself, so the oldest survives. */
function duplicateProblems(batch: readonly number[], entries: readonly PlannedIssue[]): string[] {
  const age = new Map(batch.map((number, index) => [number, index]))
  const duplicates = new Set(entries.flatMap(({ number, duplicate_of }) => (duplicate_of === undefined ? [] : [number])))
  return entries.flatMap(({ number, duplicate_of: of }) => {
    if (of === undefined) return []
    const ofAge = age.get(of)
    const numberAge = age.get(number)
    if (ofAge === undefined) return [`#${number} is a duplicate of #${of}, which is not in the batch`]
    if (of === number) return [`#${number} is a duplicate of itself`]
    if (duplicates.has(of)) return [`#${number} is a duplicate of #${of}, which is a duplicate itself`]
    if (numberAge !== undefined && ofAge > numberAge) return [`#${number} is a duplicate of #${of}, which is newer, but the oldest must survive`]
    return []
  })
}

const isRecord = (value: unknown): value is Record<string, unknown> => typeof value === 'object' && value !== null && !Array.isArray(value)

const isIssueNumber = (value: unknown): value is number => Number.isSafeInteger(value) && (value as number) > 0

const isOneOf = <T extends string>(values: readonly T[], value: unknown): value is T => values.some((each) => each === value)

const show = (value: unknown): string => (value === undefined ? 'none' : JSON.stringify(value))
